const BROWSER_LANG_MAP: Record<string, DriverLanguage> = {
  tr: 'TR',
  de: 'DE',
  fr: 'FR',
  ru: 'RU',
  ar: 'AR',
  en: 'EN',
};

const getBrowserLanguage = (): DriverLanguage => {
  const browserLang = navigator.language || (navigator as any).userLanguage || 'en';
  const primaryLang = browserLang.split('-')[0].toLowerCase();
  return BROWSER_LANG_MAP[primaryLang] || 'TR'; // Default to Turkish for drivers
};

